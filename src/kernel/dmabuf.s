;; Буферы-источники DMA в странице данных.
;;
;; DMA TS-Config работает словами и игнорирует бит 0 адреса, а SDCC не
;; выравнивает переменные: массив по нечётному адресу DMA прочитает со
;; сдвигом на байт (палитра перемешается, заливка пойдёт полосами).
;; Поэтому всё, что читает DMA из Win0/Win1, лежит здесь: область _DMABUF
;; с чётной базой (-Wl-b_DMABUF=0x7C00), размеры полей чётные.

	.module dmabuf

	.area	_DMABUF
_dma_palette::		.ds	512	; палитра для DMA RAM->CRAM (256 слов)
_dma_fill_word::	.ds	2	; слово-источник DMA FILL
