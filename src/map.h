// Карта памяти OpenXComZX: 4 МБ TS-Config = 256 физических страниц по 16 КБ (#00–#FF).
// Номера страниц и что в них лежит. Порядок: окна процессора, общие страницы (нужны обоим
// режимам), геоскейп, бой (раздел заполнится, когда появится бой).
//
// Страницы пула (#B0–#EF) раздаёт менеджер страниц (pg_alloc, src/kernel/win0/pages.s) во время
// работы: постоянного номера у них нет, здесь — кто и сколько страниц берёт.
//
// Эти значения повторяются в ассемблере и сборке — при смене править вместе:
//   tools/build.ps1 ($KERNEL_PAGE, $DATA_PAGE, $RES_PAGE, $RES_LAST, таблица $banks),
//   src/kernel/win0/crt0.s, far.s, pages.s, text.s, src/geoscape/earth/globe.s, globe_sh_s.s (равенства *_PAGE).
// Подробности — project_docs/08_ui_port_plan.md §4.
#ifndef MAP_H
#define MAP_H

// ================================================================ окна процессора
//
//   Win0 #0000–#3FFF  страница KERNEL_PAGE, не переключается, кэш
//   Win1 #4000–#7FFF  страница DATA_PAGE, не переключается, кэш
//   Win2 #8000–#BFFF  банк кода (__banked, set_bank), при выводе текста — страница шрифтов; кэш
//   Win3 #C000–#FFFF  дальние данные: ресурсы, состояние, экран, пул; без кэша (сюда пишет DMA)

// ================================================================ общие страницы

// #00–#03 — резерв. #02 стоит в Win2 при старте SPG (банк 0 таблицы bank_page).
#define PG_LOW_FIRST     0x00
#define PG_LOW_LAST      0x03

// Ядро (Win0): RST #0000–#00FF, код ядра на ассемблере #0100–#37FF (src/kernel/win0: старт,
// прерывания, джампер банков, менеджер страниц, дальняя память, ресурсы, вывод текста, ввод),
// стек #3800–#3DFF (вершина #3E00), векторы IM2 #3EFB–#3F00.
#define KERNEL_PAGE      0x04

// Данные (Win1): переменные C и ядра (_DATA #4000–#7BFF), буферы DMA с чётной базой (_DMABUF
// #7C00–#7FDF, src/kernel/dmabuf.s), заглушка входа SPG #7FE0–#7FFF.
#define DATA_PAGE        0x05

// Состояние кампании (src/inc/state.h; сохранение — дамп этих страниц, 12_game_state.md).
// На время вызовов окон диспетчер подключает STATE_PAGE в Win3.
#define STATE_PAGE       0x06      // #06 state_t: время, деньги, базы, корабли, НЛО, страны…
                                   // #07 soldier_t[MAX_SOLDIERS] (SOLDIER_PAGE, state.h)
#define STATE_PAGES      4         // #06–#09: #08–#09 — резерв кампании

// #0A–#0E — резерв.
#define PG_FREE_FIRST    0x0A
#define PG_FREE_LAST     0x0E

// Под окном FMAddr: страница, которая стоит в Win3, пока курсор пишет регистры (cursor.c).
#define SCRATCH_PAGE     0x0F

// Экран 256c: 512 x 512 точек, 16 страниц (#10–#1F, выравнивание 16), строка — 512 байт, страница —
// 32 строки: адрес точки = SCREEN_PAGE + y >> 5, смещение (y & 31) · 512 + x. Видимое окно 320x200 —
// строки 0–199 (#10–#16); строки 280–479 (#18–#1E) — задний буфер глобуса (globe.s, BACK_Y).
#define SCREEN_PAGE      0x10
#define SCREEN_PAGES     16

// TSU: листы спрайтов и тайлов, 16 страниц (#20–#2F, выравнивание 8). Сейчас — спрайт курсора
// (TS_SGPAGE, cursor.c).
#define TSU_PAGE         0x20
#define TSU_PAGES        16

// Банки кода (Win2): #30–#3F — резидентные, #40–#4F — оверлей режима (одни и те же страницы
// для геоскейпа и боя, 08 §4.3a). Решение пользователя (2026-09-18): в бою данные геоскейпа не
// нужны — бою отдаются и оверлейные банки, и страницы GEO.PAK (#60–#7F, перечитывается с SD при
// возврате), и листы TSU, и задний буфер глобуса в экране (16_battlescape_plan.md §1.3). Номер банка -> страница — таблица $banks в tools/build.ps1.
#define BANK_PAGE        0x30
#define BANK_OVL_PAGE    0x40
#define BANK_LAST        0x4F

// Общие банки
#define PG_BANK1         0x30      // ui.c — ядро интерфейса, screens.c — диспетчер окон
#define PG_BANK2         0x31      // меню, имена объектов, концовки; точки глобуса (globe_ui)
#define PG_BANK7         0x36      // сохранение, новая игра, экономика, bios (для save.c)
#define PG_BANK11        0x3A      // графика (gfx.c), курсор и опрос ввода, запуск (boot.c)
#define PG_BANK12        0x3B      // SD-карта: драйвер (sd.s), FAT, ресурсы с карты (sdres.c)
#define PG_BANK14        0x3E      // самотест джампера (test/bank_a)
#define PG_BANK15        0x3F      // самотест джампера (test/bank_b)

// Ресурсы: пакеты *.PAK, вшитые в SPG (PAL, LANG, RULES, GEO), #50–#AF (1.5 МБ). TFTD занимает
// #50–#72, UFO — #50–#6D. Большие пакеты (фоны, Уфопедия, предметы, заставки, виды глобуса) — на
// SD-карте, в пул по запросу (13_sd_card.md).
#define RES_PAGE         0x50
#define RES_LAST         0xAF

// Динамический пул: #B0–#EF (64 страницы, 1 МБ), битовая карта занятости — pages.s.
#define POOL_FIRST       0xB0
#define POOL_LAST        0xEF

// Пул — общие пользователи (страниц):
//   1   шрифты (text_init, boot.c); в хвосте с #34A0 — таблицы атласа глифов и шагов символов
//   6   атлас глифов text.s: страница на ключ (шрифт, цвет, инверсия, mul), по первому выводу
//   1   каталог пакетов с SD (sdres.c)
//   24  кэш ресурсов с SD: 6 слотов по 4 страницы (sdres.c)
//   2   слот сохранения в памяти, на каждый использованный слот (до 10, save.c)

// #F0–#FF — не трогать: загрузчики, TS-BIOS, vDOS. Менеджер страниц их не выдаёт.
#define RESERVED_PAGE    0xF0

// ================================================================ геоскейп

// Банки геоскейпа: окна
#define PG_BANK3         0x32      // геоскейп: главное окно (scr_geo.c)
#define PG_BANK4         0x33      // геоскейп: окна-2, графики
#define PG_BANK5         0x34      // базы: окна
#define PG_BANK6         0x35      // базы: окна-2
#define PG_BANK9         0x38      // исследования и производство: окна
#define PG_BANK10        0x39      // корабли: окна
#define PG_BANK13        0x3C      // Уфопедия
// Банки геоскейпа: логика
#define PG_BANK8         0x37      // игровое время, лаборатория
#define PG_BANK16        0x3D      // конец месяца
// Банки геоскейпа: оверлей
#define PG_BANK17        0x40      // ГСЧ, регионы, сфера, маска суши (world.c, geo.c)
#define PG_BANK18        0x41      // стратегия и миссии пришельцев
#define PG_BANK19        0x42      // НЛО, обнаружение, места миссий, базы пришельцев
#define PG_BANK20        0x43      // полёты кораблей X-COM
#define PG_BANK21        0x44      // окна полёта: перехват, корабль, цель
#define PG_BANK22        0x45      // воздушный бой: логика
#define PG_BANK23        0x46      // воздушный бой: окна
#define PG_BANK24        0x47      // глобус: кадр, рёбра, проход строк (globe.s, globe_s.s), с #BC00 — таблица квадратов
#define PG_BANK25        0x48      // глобус: тень, предрасчитанные виды; с #B800 — рабочие таблицы тени
#define PG_BANK26        0x49      // глобус: детали, метки; с #A800 — рабочая память

// Пул — геоскейп (страниц, globe.md):
//   1   рабочая страница глобуса: таблицы произведений вида, проекции, корзины (globe.s, work)
//   8   узоры текстур глобуса по 3 масштабам (globe.s, strip)
//   1   страница рёбер: пул рёбер, записи строк, поток предрасчитанного вида (globe.s, epage)
//   3   образцы уровней тени по 8 строк и флаги строк (globe_sh.s, shp)

// ================================================================ бой

// Пока нет. Оверлей боя займёт банки #40–#4F (вместо оверлея геоскейпа) и страницы пула под карту
// боя и графику миссии.

#endif
